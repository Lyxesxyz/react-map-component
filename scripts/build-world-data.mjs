// Regenerates packages/geospatial-map-core/src/world-data.ts, the outline data behind
// `worldBasemap`, then syncs it into the React and Angular folders (scripts/sync-core.mjs).
// Source: Natural Earth 1:110m admin-0 countries (public domain), via the world-atlas package.
// Run: node scripts/build-world-data.mjs
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath, URL } from 'node:url'

const require = createRequire(new URL('../apps/demo/package.json', import.meta.url))
const { feature } = require('topojson-client')
const topology = require('world-atlas/countries-110m.json')

const round = (value) => Math.round(value * 100) / 100
const jumps = (ring) =>
  ring.filter((point, index) => index > 0 && Math.abs(point[0] - ring[index - 1][0]) > 180).length

// Keeps the part of a closed ring on one side of the line x = 180 (Sutherland–Hodgman).
function clip(ring, keepWest) {
  const inside = (point) => (keepWest ? point[0] <= 180 : point[0] >= 180)
  const result = []
  for (let index = 0; index < ring.length - 1; index++) {
    const current = ring[index]
    const next = ring[index + 1]
    if (inside(current)) result.push(current)
    if (inside(current) !== inside(next)) {
      const ratio = (180 - current[0]) / (next[0] - current[0])
      result.push([180, current[1] + ratio * (next[1] - current[1])])
    }
  }
  if (result.length) result.push(result[0])
  return result
}

// A ring that crosses the antimeridian and comes back (Russia, Fiji) is made continuous past
// 180° and cut in two there. Antarctica crosses once, around the pole, and is kept as it is.
function splitAtAntimeridian(polygon) {
  if (jumps(polygon[0]) !== 2) return [polygon]
  const continuous = polygon[0].map(([x, y]) => [x < 0 ? x + 360 : x, y])
  const west = clip(continuous, true)
  const east = clip(continuous, false).map(([x, y]) => [x - 360, y])
  return [west, east].filter((ring) => ring.length >= 4).map((ring) => [ring])
}

const polygons = feature(topology, topology.objects.countries).features.flatMap((country) => {
  const geometry = country.geometry
  const list = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  return list
    .flatMap(splitAtAntimeridian)
    .map((polygon) => polygon.map((ring) => ring.map(([x, y]) => [round(x), round(y)])))
})
const encoded = polygons.map((polygon) =>
  polygon.map((ring) => {
    const flat = []
    let px = 0
    let py = 0
    for (const [x, y] of ring) {
      const ix = Math.round(x * 100)
      const iy = Math.round(y * 100)
      flat.push(ix - px, iy - py)
      px = ix
      py = iy
    }
    return flat
  }),
)
const target = new URL('../packages/geospatial-map-core/src/world-data.ts', import.meta.url)
writeFileSync(
  target,
  [
    '// Generated by scripts/build-world-data.mjs. Do not edit.',
    '// Natural Earth 1:110m country outlines (public domain), via world-atlas.',
    '// One entry per polygon, one array per ring: [x0, y0, dx1, dy1, …] in 1/100 degree.',
    `export const worldOutlines: number[][][] = ${JSON.stringify(encoded)}`,
    '',
  ].join('\n'),
)
console.log(`Wrote ${encoded.length} polygons to ${target.pathname}`)
execFileSync(process.execPath, [fileURLToPath(new URL('sync-core.mjs', import.meta.url))], {
  stdio: 'inherit',
})
